function getIstanbulDayMonth(now: Date): { day: number; month: number } {
  try {
    const parts = new Intl.DateTimeFormat("en-US", {
      timeZone: "Europe/Istanbul",
      day: "numeric",
      month: "numeric",
    }).formatToParts(now);
    const day = Number(parts.find((p) => p.type === "day")?.value);
    const month = Number(parts.find((p) => p.type === "month")?.value);
    if (Number.isFinite(day) && Number.isFinite(month)) {
      return { day, month };
    }
  } catch {
    // fallback below
  }
  return { day: now.getDate(), month: now.getMonth() + 1 };
}

export function getTodayHistoricalEvent(
  now: Date = new Date(),
): HistoricalEvent {
  const { day, month } = getIstanbulDayMonth(now);

  const exact = fenerbahceHistoryEvents.find(
    (e) => e.day === day && e.month === month,
  );
  if (exact) return exact;

  const sameMonth = fenerbahceHistoryEvents
    .filter((e) => e.month === month)
    .sort((a, b) => Math.abs(a.day - day) - Math.abs(b.day - day));
  if (sameMonth.length > 0) return sameMonth[0];

  const idx = (day + month) % fenerbahceHistoryEvents.length;
  return fenerbahceHistoryEvents[idx];
}
